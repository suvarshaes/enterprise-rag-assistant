import os
from typing import List, Dict, Any, Optional

from pydantic import BaseModel

import numpy as np
import pandas as pd
from fastapi import FastAPI, File, Form, HTTPException, UploadFile
from openai import OpenAI
from pypdf import PdfReader

app = FastAPI(title="Enterprise RAG Microservie")

# Connect the OpenAI SDK to your local Ollama server (free, no API key needed)
client = OpenAI(
    base_url="http://localhost:11434/v1",
    api_key="ollama",
)

EMBEDDING_MODEL = "nomic-embed-text"
CHAT_MODEL = "llama3.2"

class ChunkPayload(BaseModel):
    # Describes one small piece of PDF text after it has been processed.
    chunk_index: int  # The chunk's position in the list, starting with 0.
    page_number: int  # The PDF page where this chunk came from.
    section_title: Optional[str] = None  # An optional name for this part of the document.
    content: str  # The actual text contained in this chunk.
    embedding: List[float]  # Numbers that represent the chunk's meaning for similarity search.

class IngestResponse(BaseModel):
    # Describes the information returned after a PDF is processed.
    page_count: int  # The total number of pages found in the PDF.
    chunks: List[ChunkPayload]  # All text chunks created from the PDF.

class RetrievedChunk(BaseModel):
    # Describes a stored PDF chunk that can be used to answer a question.
    chunk_id: str  # A unique identifier for this text chunk.
    document_id: str  # A unique identifier for the source PDF.
    file_name: str  # The original name of the uploaded PDF.
    page_number: int  # The PDF page that contains this text.
    section_title: Optional[str] = None  # An optional label for the document section.
    content: str  # The text that may help answer the question.
    embedding: List[float]  # Numbers used to measure how relevant this chunk is.

class AskRequest(BaseModel):
    # Describes everything sent when asking a question.
    question: str  # The question submitted by the user.
    domain: Optional[str] = None  # An optional subject area, such as finance or clinical trials.
    candidates: List[RetrievedChunk]  # Possible source chunks that may answer the question.
    top_k: int = 5  # The maximum number of most relevant chunks to use.


class CitationItem(BaseModel):
    # Describes one source cited in the generated answer.
    citation_id: str  # The bracketed reference label, such as C1 or C2.
    chunk_id: str  # The unique identifier of the cited text chunk.
    document_id: str  # The unique identifier of the source PDF.
    file_name: str  # The name of the cited PDF.
    page_number: int  # The page containing the cited text.
    section_title: Optional[str] = None  # An optional label for the cited section.
    excerpt: str  # A short preview of the cited text.


class AskResponse(BaseModel):
    # Describes the final answer returned to the caller.
    answer: str  # The text generated by the chat model.
    citations: List[CitationItem]  # The source documents that support the answer.

def chunk_page_text(
    text: str, page_number: int, chunk_size: int = 900, overlap: int = 150
) -> List[tuple[int, str]]:
    # Split a page into smaller, overlapping pieces that are easier to search and embed.
    # Preserve word boundaries by collapsing repeated whitespace into single spaces.
    cleaned = " ".join(text.split())
    if not cleaned:
        return []

    chunks: List[tuple[int, str]] = []
    start = 0
    while start < len(cleaned):
        end = min(start + chunk_size, len(cleaned))
        chunks.append((page_number, cleaned[start:end]))
        if end == len(cleaned):
            break
        start += max(1, chunk_size - overlap)
    return chunks

def embed_texts(texts: List[str]) -> List[List[float]]:
    # Convert text into number lists that the service can compare for similarity.
    if not texts:
        return []
    resp = client.embeddings.create(model=EMBEDDING_MODEL, input=texts)
    return [item.embedding for item in resp.data]

def cosine_similarity(a: np.ndarray, b: np.ndarray) -> float:
    # Measure how similar two embeddings are; 1 means very similar and 0 means unrelated.
    denom = float(np.linalg.norm(a) * np.linalg.norm(b))
    if denom == 0.0:
        return 0.0
    return float(np.dot(a, b) / denom)

@app.post("/ingest", response_model=IngestResponse)
async def ingest_pdf(file: UploadFile = File(...), domain: str = Form("General")):
    # Read an uploaded PDF, split its text into chunks, and create an embedding for each chunk.
    if not file.filename or not file.filename.lower().endswith(".pdf"):
        raise HTTPException(status_code=400, detail="Only PDF files are supported.")

    # Open and inspect the PDF to find out how many pages it contains.
    reader = PdfReader(file.file)
    page_count = len(reader.pages)

    # Read each page, extract its text, and split it into searchable chunks.
    raw_chunks: List[tuple[int, str]] = []
    for page_num, page in enumerate(reader.pages, start=1):
        page_text = page.extract_text() or ""
        for p_num, chunk_str in chunk_page_text(page_text, page_num):
            raw_chunks.append((p_num, chunk_str))

    if not raw_chunks:
        raise HTTPException(
            status_code=400, detail="Could not extract text from PDF."
        )

    # Ask Ollama to convert every chunk into a list of meaning-based numbers.
    embeddings = embed_texts([c[1] for c in raw_chunks])

    # Combine each chunk with its page number, title, text, and embedding.
    payload = [
        ChunkPayload(
            chunk_index=idx,
            page_number=page_num,
            section_title=f"{domain} Page {page_num}",
            content=text,
            embedding=emb,
        )
        for idx, ((page_num, text), emb) in enumerate(zip(raw_chunks, embeddings))
    ]

    return IngestResponse(page_count=page_count, chunks=payload)


@app.post("/answer", response_model=AskResponse)
async def answer_with_citations(req: AskRequest):
    # Rank source chunks against the question, then ask the chat model to answer using those sources.
    if not req.candidates:
        return AskResponse(
            answer="No relevant document chunks were found to answer this question.",
            citations=[],
        )

    # Convert the user's question into the same number format as the document chunks.
    q_emb = np.array(embed_texts([req.question])[0], dtype=np.float32)

    # Compare the question with every candidate chunk.
    scored: List[tuple[float, RetrievedChunk]] = []
    for c in req.candidates:
        c_emb = np.array(c.embedding, dtype=np.float32)
        score = cosine_similarity(q_emb, c_emb)
        scored.append((score, c))

    # Keep the highest-scoring chunks, limited by top_k.
    scored.sort(key=lambda x: x[0], reverse=True)
    top_chunks = [c for _, c in scored[: req.top_k]]

    # Build numbered source blocks and remember which chunk belongs to each number.
    context_blocks: List[str] = []
    citation_map: dict[str, RetrievedChunk] = {}

    for idx, chunk in enumerate(top_chunks, start=1):
        tag = f"C{idx}"
        citation_map[tag] = chunk
        context_blocks.append(
            f"[{tag}] (File: {chunk.file_name}, Page: {chunk.page_number}, "
            f"Section: {chunk.section_title or 'N/A'})\n{chunk.content}"
        )

    # Give the chat model rules so it relies on the provided sources and marks claims.
    system_prompt = (
        "You are an enterprise document analyst for clinical trials and financial reports. "
        "Answer strictly using the provided source blocks. "
        "Inline-cite claims using bracketed tags like [C1], [C2]. "
        "If the provided context does not contain enough information, explicitly state what is missing. "
        "Be precise with numbers, dates, cohorts, endpoints, and accounting figures."
    )

    user_prompt = (
        f"Question: {req.question}\n\n"
        f"Sources:\n" + "\n\n".join(context_blocks)
    )

    # Send the question and source text to Ollama's chat model.
    completion = client.chat.completions.create(
        model=CHAT_MODEL,
        temperature=0.1,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
    )

    answer_text = completion.choices[0].message.content or ""

    # Return citation details only for source labels actually mentioned in the answer.
    citations = [
        CitationItem(
            citation_id=tag,
            chunk_id=chunk.chunk_id,
            document_id=chunk.document_id,
            file_name=chunk.file_name,
            page_number=chunk.page_number,
            section_title=chunk.section_title,
            excerpt=chunk.content[:240]
            + ("..." if len(chunk.content) > 240 else ""),
        )
        for tag, chunk in citation_map.items()
        if f"[{tag}]" in answer_text
    ]

    return AskResponse(answer=answer_text, citations=citations)